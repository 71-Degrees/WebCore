using System.Collections.Concurrent;
using System.Security.Cryptography;
using Microsoft.Extensions.FileProviders;

namespace WebCore.Hosting.Assets;

/// <summary>
/// Appends a content-hash query string to a wwwroot-relative asset path (e.g. "js/avatar.js" ->
/// "js/avatar.js?v=3f8a1c2e"), so a browser's aggressive static-file caching can never keep
/// serving a stale copy after a deploy - the version changes automatically whenever the file's
/// bytes change, with no number to remember to bump by hand. That manual-bump gap is exactly what
/// broke avatar.js earlier: its behavior changed but the script tag didn't, so browsers with an
/// already-cached copy kept running the old code against new server-side expectations. Hashes are
/// computed once per file and cached for the process lifetime - wwwroot content doesn't change
/// without a redeploy (a fresh process), so there's nothing to invalidate mid-process.
/// </summary>
public class StaticAssetVersion
{
    private readonly IFileProvider _files;
    private readonly ConcurrentDictionary<string, string?> _cache = new();

    // The web root's file provider, not a folder path: it also sees files that are not in wwwroot on disk while developing - the scoped-styles bundle
    // (TriviaNight.Web.styles.css) is generated by the build and served from a static web assets manifest, so a plain File.Exists on wwwroot would miss it.
    public StaticAssetVersion(IWebHostEnvironment env)
        : this(env.WebRootFileProvider)
    {
    }

    public StaticAssetVersion(IFileProvider files)
    {
        _files = files;
    }

    public string Url(string relativePath)
    {
        var hash = _cache.GetOrAdd(relativePath, ComputeHash);
        return hash is null ? relativePath : $"{relativePath}?v={hash}";
    }

    private string? ComputeHash(string relativePath)
    {
        var file = _files.GetFileInfo(relativePath);
        if (!file.Exists)
        {
            return null;
        }

        using var stream = file.CreateReadStream();
        var hashBytes = SHA256.HashData(stream);
        return Convert.ToHexString(hashBytes)[..8].ToLowerInvariant();
    }
}
